// Prints the merged monolith schema to apps/bff/schema.graphql and checks the persisted operations against it.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { printSchemaWithDirectives } from '@graphql-tools/utils';
import { parse, validate } from 'graphql';
import { buildBffSchema } from '../apps/bff/src/schema';

const BFF_DIR = join(import.meta.dirname, '..', 'apps', 'bff');
const OPERATIONS_DIR = join(BFF_DIR, 'persisted-operations');

const schema = buildBffSchema();

writeFileSync(
  join(BFF_DIR, 'schema.graphql'),
  `# GENERATED by scripts/print-schema.ts. Do not edit: change the module .graphql files instead.\n\n${printSchemaWithDirectives(schema)}\n`,
);

let failed = false;
for (const file of readdirSync(OPERATIONS_DIR).filter((name) => name.endsWith('.graphql'))) {
  const errors = validate(schema, parse(readFileSync(join(OPERATIONS_DIR, file), 'utf8')));
  for (const error of errors) {
    failed = true;
    console.error(`${file}: ${error.message}`);
  }
}

if (failed) process.exit(1);
console.info('apps/bff/schema.graphql written; all persisted operations are valid.');
