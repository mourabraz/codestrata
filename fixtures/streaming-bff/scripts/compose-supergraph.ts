// Composes the subgraph schemas into apps/router/supergraph.graphql (what `rover supergraph compose` does in CI).
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { composeServices } from '@apollo/composition';
import { parse } from 'graphql';
import {
  SUBGRAPH_NAME as AVAILABILITY,
  availabilitySubgraphSdl,
} from '../apps/availability-subgraph/src/schema';
import { SUBGRAPH_NAME as CATALOG, catalogSubgraphSdl } from '../apps/catalog-subgraph/src/schema';

const result = composeServices([
  { name: CATALOG, url: 'http://localhost:4101/graphql', typeDefs: parse(catalogSubgraphSdl()) },
  { name: AVAILABILITY, url: 'http://localhost:4102/graphql', typeDefs: parse(availabilitySubgraphSdl()) },
]);

if (result.errors) {
  for (const error of result.errors) console.error(error.message);
  process.exit(1);
}

writeFileSync(
  join(import.meta.dirname, '..', 'apps', 'router', 'supergraph.graphql'),
  `# GENERATED by scripts/compose-supergraph.ts. Do not edit.\n${result.supergraphSdl}`,
);
console.info('apps/router/supergraph.graphql written.');
